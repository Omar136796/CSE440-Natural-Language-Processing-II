print("Deep Confusion Matrix:\n", confusion_matrix(y_test, y_pred_deep))

y_prob_shallow = imdb_model.predict(x_test_pad, verbose=0).ravel()
y_pred_shallow = (y_prob_shallow >= 0.5).astype(int)

print(classification_report(y_test, y_pred_shallow))
print("Shallow Confusion Matrix:\n", confusion_matrix(y_test, y_pred_shallow))

