import numpy as np
import matplotlib.pyplot as plt
import time
from sklearn.datasets import load_wine
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from tensorflow.keras.models import Sequential
from tensorflow.keras.utils import to_categorical
from tensorflow.keras.layers import Dense, Embedding, Dropout, GlobalAveragePooling1D
from tensorflow.keras.datasets import imdb
from tensorflow.keras.preprocessing.sequence import pad_sequences
from tensorflow.keras.optimizers import Adam
from sklearn.metrics import roc_curve, auc, confusion_matrix, ConfusionMatrixDisplay, classification_report

"""# Task 01"""

wine=load_wine()
X=wine.data
y=wine.target

X_train,X_test,y_train,y_test=train_test_split(X,y,test_size=0.25,random_state=42,stratify=y)

scaler=StandardScaler()
X_train=scaler.fit_transform(X_train)
X_test=scaler.transform(X_test)

y_train_class=to_categorical(y_train,num_classes=3)
y_test_class=to_categorical(y_test,num_classes=3)

model=Sequential([
    Dense(64,activation='relu',input_shape=(X_train.shape[1],)),
    Dense(3,activation='softmax') # output layer
])

model.compile(optimizer='adam',loss='categorical_crossentropy',metrics=['accuracy'])

model.summary()

history=model.fit(X_train,y_train_class,epochs=100,batch_size=16,validation_split=0.2,verbose=1)

test_loss,test_accuracy=model.evaluate(X_test,y_test_class,verbose=0)
print(f"Test Accuracy: {test_accuracy}")

# Loss plot
plt.figure()
plt.plot(history.history['loss'],label='Training Loss')
plt.plot(history.history['val_loss'],label='Validation Loss')
plt.xlabel('Epochs')
plt.ylabel('Loss')
plt.legend()
plt.title('Training Loss vs Validation Loss')
plt.show()

# Accuracy plot
plt.figure()
plt.plot(history.history['accuracy'],label='Training Accuracy')
plt.plot(history.history['val_accuracy'],label='Validation Accuracy')
plt.xlabel('Epochs')
plt.ylabel('Accuracy')
plt.legend()
plt.title('Training Accuracy vs Validation Accuracy')
plt.show()

"""# Task 02"""

vocab_size=15000
max_len=200

(x_all_train, y_all_train),(x_test, y_test)=imdb.load_data(num_words=vocab_size)
print(f"Training samples: {len(x_all_train)}, Test samples: {len(x_test)}")

x_train, x_val, y_train, y_val = train_test_split(
    x_all_train, y_all_train,
    test_size=0.25,
    random_state=42,
    stratify=y_all_train
)

x_train_pad = pad_sequences(x_train, maxlen=max_len)
x_val_pad   = pad_sequences(x_val, maxlen=max_len)
x_test_pad  = pad_sequences(x_test, maxlen=max_len)

imdb_model = Sequential([
    Embedding(input_dim=vocab_size, output_dim=64, input_length=max_len),         # embedding layer
    GlobalAveragePooling1D(),                                                     # reduces overfitting
    Dense(64, activation='relu'),                                                 # hidden layer
    Dense(1, activation='sigmoid')                                                # output layer
])

imdb_model.compile(
    optimizer='adam',
    loss='binary_crossentropy',
    metrics=['accuracy']
)

imdb_model.summary()

start_time1 = time.time()
history_imdb = imdb_model.fit(
    x_train_pad, y_train,
    epochs=12,
    batch_size=128,
    validation_data=(x_val_pad, y_val),
    verbose=1
)

training_time_shallow = time.time() - start_time1
print(f"Shallow Training time: {training_time_shallow:.1f} seconds")

test_loss, test_accuracy = imdb_model.evaluate(x_test_pad, y_test, verbose=0)
print(f"Test Accuracy: {test_accuracy:.4f} | Test Loss: {test_loss:.4f}")

y_pred_probs = imdb_model.predict(x_test_pad, verbose=0).ravel()
y_pred_class = (y_pred_probs >= 0.5).astype(int)

print(classification_report(y_test, y_pred_class, target_names=['Negative', 'Positive']))

false_pos_rate, true_pos_rate, thresholds = roc_curve(y_test, y_pred_probs)
roc_auc = auc(false_pos_rate, true_pos_rate)
print(f"AUC: {roc_auc:.4f}")

plt.figure(figsize=(6,5))
plt.plot(history_imdb.history['accuracy'], label='train acc')
plt.plot(history_imdb.history['val_accuracy'], label='val acc')
plt.title('Accuracy')
plt.xlabel('Epoch'); plt.ylabel('Accuracy')
plt.legend(); plt.grid(True)

plt.show()

plt.figure(figsize=(6,5))
plt.plot(history_imdb.history['loss'], label='train loss')
plt.plot(history_imdb.history['val_loss'], label='val loss')
plt.title('Loss')
plt.xlabel('Epoch'); plt.ylabel('Loss')
plt.legend(); plt.grid(True)

plt.show()

plt.figure(figsize=(6,5))
plt.plot(false_pos_rate, true_pos_rate, label=f'AUC = {roc_auc:.3f}', color='darkblue')
plt.plot([0,1], [0,1], 'k--', label='Random')
plt.xlabel('False Positive Rate'); plt.ylabel('True Positive Rate')
plt.title('ROC Curve')
plt.legend(); plt.grid(True)
plt.show()

