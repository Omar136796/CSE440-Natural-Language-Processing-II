french_text=udhr.raw('French_Francais-Latin1')
print(french_text)

"""Extracting the sequence of vowels"""

french_words=word_tokenize(french_text.lower())
print(french_words)

all_vowels='aeiouyàâäéèêëîïôöùûüÿ'

list1=[]

for w in french_words:
    str1=''
    for letter in w:
        if letter in all_vowels:
            str1 += letter
    if str1 != '':
        list1.append(str1)
print(list1)

""" Generating all possible bigrams of consecutive vowels"""

vowel_bigrams=[]
for seq in list1:
    vowel_bigrams.extend(list(ngrams(seq, 2)))    # extend na korle prottek word alada list e jay. append korle
print(vowel_bigrams)

"""Building a frequency distribution"""

frequency=FreqDist(vowel_bigrams)

frequency

