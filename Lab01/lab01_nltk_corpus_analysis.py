from nltk.corpus import state_union
import numpy as np

state_union.fileids()

"""Choosing a text file from the State of the Union corpus in NLTK"""

text1=state_union.raw('1945-Truman.txt')
#print(text1)

"""Converting it to lowercase"""

text2=text1.lower()
#print(text2)

"""Removing punctuation"""

import string

text3 = text2.translate(str.maketrans('','',string.punctuation))

#print(text3)

"""Filtering out stopwords"""

words1=word_tokenize(text3)        # text theke word gula alada

stop_words=stopwords.words('english')

filtered_words=[]

for w in words1:
  if w.lower() not in stop_words:
    filtered_words.append(w)

print(filtered_words)

"""Identifying the top 10 most frequent words"""

word_count=FreqDist(filtered_words)
common=word_count.most_common(10)
print(common)

"""Applying trigrams"""

from nltk.util import ngrams

trigrams=list(ngrams(filtered_words,n=3))

print(trigrams)

"""Building co-occurrence matrix"""

top10words = []
for tup in common:
    top10words.append(tup[0])

print(top10words)

word_to_index = {}
for i in range(len(top10words)):
    word_to_index[top10words[i]] = i
print(word_to_index)

co_matrix = np.zeros((10, 10), dtype=int)

for tri in trigrams:
    for i in range(3):
        for j in range(i+1, 3):
            w1, w2 = tri[i], tri[j]
            if w1 in word_to_index and w2 in word_to_index:
                idx1=word_to_index[w1]
                idx2=word_to_index[w2]
                co_matrix[idx1, idx2]+=1
                co_matrix[idx2, idx1]+=1

print(co_matrix)

