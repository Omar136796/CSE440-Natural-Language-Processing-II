import numpy as np
from sklearn.metrics.pairwise import cosine_similarity

def listAdd(list1,list2):
    list3=[]
    for i in range(len(list1)):
        list3.append(float(list1[i])+float(list2[i]))
    return list3

def listSub(list1,list2):
    list3=[]
    for i in range(len(list1)):
        list3.append(float(list1[i])-float(list2[i]))
    return list3

glove_file = "glove.6B.100d.txt"

def load_glove_model(glove_file):
    word_vectors={}

    with open(glove_file, 'r', encoding='utf-8') as f:
        for line in f:
            values=line.split()
            word=values[0]

            vector=np.array(values[1:], dtype='float32')
            word_vectors[word]=vector
    return word_vectors

glove_model=load_glove_model(glove_file)

def find_closest_word(target_vector, glove_model, exclude_words):

    similarities = []

    for word, vector in glove_model.items():
        if word not in exclude_words:
            sim=cosine_similarity([target_vector], [vector])
            sim=sim[0][0]
            similarities.append((word, sim))

    similarities.sort(key=lambda x: x[1], reverse=True)

    return similarities[0]

